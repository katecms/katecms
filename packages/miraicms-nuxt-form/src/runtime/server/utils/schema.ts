import { sql } from 'kysely'
import { getFormDb, isPostgresDriver } from './db'

export async function ensureFormTables(): Promise<void> {
  const db = getFormDb()
  if (isPostgresDriver()) {
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_forms (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        slug text NOT NULL,
        status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
        content text NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      )
    `.execute(db)
    await sql`CREATE UNIQUE INDEX IF NOT EXISTS miraicms_forms_slug ON miraicms_forms (slug)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_submissions (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        form_id integer NOT NULL,
        ip text NOT NULL DEFAULT '',
        created_at timestamptz NOT NULL DEFAULT now()
      )
    `.execute(db)
    await sql`CREATE INDEX IF NOT EXISTS miraicms_form_submissions_form ON miraicms_form_submissions (form_id)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_submission_values (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        submission_id integer NOT NULL,
        field_key text NOT NULL,
        value text NOT NULL
      )
    `.execute(db)
    await sql`CREATE INDEX IF NOT EXISTS miraicms_form_submission_values_submission ON miraicms_form_submission_values (submission_id)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_mail (
        id integer PRIMARY KEY CHECK (id = 1),
        host text NOT NULL DEFAULT '',
        port integer NOT NULL DEFAULT 587,
        encryption text NOT NULL DEFAULT 'starttls' CHECK (encryption IN ('none', 'starttls', 'ssl')),
        username text NOT NULL DEFAULT '',
        password text NOT NULL DEFAULT '',
        from_email text NOT NULL DEFAULT '',
        from_name text NOT NULL DEFAULT ''
      )
    `.execute(db)
  }
  else {
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_forms (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        slug TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
        content TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
        updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
      )
    `.execute(db)
    await sql`CREATE UNIQUE INDEX IF NOT EXISTS miraicms_forms_slug ON miraicms_forms (slug)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_submissions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        form_id INTEGER NOT NULL,
        ip TEXT NOT NULL DEFAULT '',
        created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
      )
    `.execute(db)
    await sql`CREATE INDEX IF NOT EXISTS miraicms_form_submissions_form ON miraicms_form_submissions (form_id)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_submission_values (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        submission_id INTEGER NOT NULL,
        field_key TEXT NOT NULL,
        value TEXT NOT NULL
      )
    `.execute(db)
    await sql`CREATE INDEX IF NOT EXISTS miraicms_form_submission_values_submission ON miraicms_form_submission_values (submission_id)`.execute(db)
    await sql`
      CREATE TABLE IF NOT EXISTS miraicms_form_mail (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        host TEXT NOT NULL DEFAULT '',
        port INTEGER NOT NULL DEFAULT 587,
        encryption TEXT NOT NULL DEFAULT 'starttls' CHECK (encryption IN ('none', 'starttls', 'ssl')),
        username TEXT NOT NULL DEFAULT '',
        password TEXT NOT NULL DEFAULT '',
        from_email TEXT NOT NULL DEFAULT '',
        from_name TEXT NOT NULL DEFAULT ''
      )
    `.execute(db)
  }
  await sql`
    INSERT INTO miraicms_form_mail (id)
    SELECT 1
    WHERE NOT EXISTS (SELECT 1 FROM miraicms_form_mail WHERE id = 1)
  `.execute(db)
}
